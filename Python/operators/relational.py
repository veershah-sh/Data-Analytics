"""
2. Comparison Operators(Relational Operators)
-> always returns boolean value (True/False)

    == -> is equals to -> a == b
    != -> not equals to -> a != b
    > -> greater than -> a > b
    >= -> greater than "OR" equals to 
        -> a >= b ( returns true in 2 conditions)
            -> if a is greater than b
            -> if a is equals to b
    < -> less than -> a < b
    <= -> less than "OR" equals to
        -> a <= b ( returns true in 2 conditions)
            -> if a is less than b
            -> if a is equals to b
"""

a = 10
b = 100

print(a==b)
print(a!=b)









