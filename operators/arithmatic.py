"""
1. Arithmatic Operators
    + -> addition -> 7+6
    - -> subtraction -> 25-20
    * -> multiplication -> 9*2
    / -> division(Q) -> 4/2 -> float(2.0)
    // -> division(Q) -> 4/2 -> int(2)
    % -> division(R) -> 4/2
"""

a = 20
b = 5

print(f"{a} + {b} = {a+b}")
print(f"{a} - {b} = {a-b}")
print(f"{a} * {b} = {a*b}")
print(f"{a} / {b} = {a/b}")
print(f"{a} // {b} = {a//b}")
print(f"{9} % {3} = {9%3}")